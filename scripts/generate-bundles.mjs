import { mkdir, readdir, readFile, rm, writeFile, cp, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const inputDir = path.join(root, "input");
const publicBundles = path.join(root, "public", "bundles");
const outFile = path.join(root, "src", "utils", "bundleRegistry.generated.ts");

const toPosix = (p) => p.split(path.sep).join("/");

const readText = async (file, label) => {
  try {
    return await readFile(file, "utf8");
  } catch (error) {
    // Missing files are tolerated (the loader applies defaults); anything else is fatal.
    if (error && error.code === "ENOENT") return null;
    throw new Error(`Failed to read ${label}: ${error.message}`);
  }
};

const readJson = async (file, label) => {
  const text = await readText(file, label);
  if (text === null) return null;
  try {
    return JSON.parse(text);
  } catch (error) {
    throw new Error(`Malformed JSON in ${label}: ${error.message}`);
  }
};

const walkFiles = async (dir, base = "") => {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      files.push(...(await walkFiles(path.join(dir, entry.name), rel)));
    } else if (entry.isFile()) {
      files.push(rel);
    }
  }
  return files;
};

const listProjects = async () => {
  let entries;
  try {
    entries = await readdir(inputDir, { withFileTypes: true });
  } catch {
    return [];
  }
  return entries
    .filter((e) => e.isDirectory() && !e.name.startsWith("."))
    .map((e) => e.name);
};

const main = async () => {
  const projects = await listProjects();
  const registry = {};
  const parsed = [];
  const errors = [];
  const warnings = [];

  // 1. Validate every bundle BEFORE touching public/ or the registry, so a bad
  //    JSON file fails loudly instead of silently becoming `null`.
  for (const id of projects) {
    const dir = path.join(inputDir, id);
    try {
      const styleguide = await readJson(
        path.join(dir, "styleguide.json"),
        `input/${id}/styleguide.json`,
      );
      const content = await readJson(
        path.join(dir, "content.json"),
        `input/${id}/content.json`,
      );
      const prompt = await readText(
        path.join(dir, "prompt.txt"),
        `input/${id}/prompt.txt`,
      );
      if (styleguide === null) {
        warnings.push(
          `input/${id}/styleguide.json is missing; engine defaults will be used.`,
        );
      }
      if (content === null) {
        warnings.push(
          `input/${id}/content.json is missing; bundle will render no scenes.`,
        );
      }
      parsed.push({ id, dir, styleguide, content, prompt });
    } catch (error) {
      errors.push(error instanceof Error ? error.message : String(error));
    }
  }

  for (const warning of warnings) console.warn(`warning: ${warning}`);

  if (errors.length > 0) {
    console.error("\nBundle registry build failed:");
    for (const message of errors) console.error(`  - ${message}`);
    console.error(
      "\nFix the malformed file(s) above and run `npm run bundles` again.",
    );
    process.exit(1);
  }

  await rm(publicBundles, { recursive: true, force: true });
  await mkdir(publicBundles, { recursive: true });

  for (const { id, dir, styleguide, content, prompt } of parsed) {
    let files = [];
    const sourcesDir = path.join(dir, "sources");
    const hasSources = await stat(sourcesDir).then(
      (s) => s.isDirectory(),
      () => false,
    );
    if (hasSources) {
      files = (await walkFiles(sourcesDir)).map((f) => `sources/${f}`);
      await cp(sourcesDir, path.join(publicBundles, id, "sources"), {
        recursive: true,
      });
    }

    registry[id] = { styleguide, content, prompt, files };
    console.log(
      `bundle "${id}": styleguide=${Boolean(styleguide)} content=${Boolean(content)} prompt=${Boolean(prompt)} assets=${files.length}`,
    );
  }

  const header = [
    "// AUTO-GENERATED by scripts/generate-bundles.mjs. Do not edit by hand.",
    '// Run `npm run bundles` to regenerate after changing anything in input/.',
    'import type { RawBundle } from "./projectLoader";',
    "",
    "",
  ].join("\n");

  const body = `export const BUNDLE_REGISTRY: Record<string, RawBundle> = ${JSON.stringify(
    registry,
    null,
    2,
  )};\n\nexport const BUNDLE_IDS: string[] = Object.keys(BUNDLE_REGISTRY);\n`;

  await writeFile(outFile, header + body, "utf8");
  console.log(`Wrote ${toPosix(path.relative(root, outFile))}`);
};

main().catch((err) => {
  console.error("\nBundle registry build failed:");
  console.error(err instanceof Error ? err.message : String(err));
  process.exit(1);
});
