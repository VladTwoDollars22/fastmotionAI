import { mkdir, readdir, readFile, rm, writeFile, cp, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const inputDir = path.join(root, "input");
const publicBundles = path.join(root, "public", "bundles");
const outFile = path.join(root, "src", "utils", "bundleRegistry.generated.ts");

const toPosix = (p) => p.split(path.sep).join("/");

const readJson = async (file) => {
  try {
    return JSON.parse(await readFile(file, "utf8"));
  } catch {
    return null;
  }
};

const readText = async (file) => {
  try {
    return await readFile(file, "utf8");
  } catch {
    return null;
  }
};

const walkFiles = async (dir, base = "") => {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      files.push(...(await walkFiles(path.join(dir, entry.name), rel)));
    } else if (entry.isFile()) {
      files.push(rel);
    }
  }
  return files;
};

const listProjects = async () => {
  let entries;
  try {
    entries = await readdir(inputDir, { withFileTypes: true });
  } catch {
    return [];
  }
  return entries
    .filter((e) => e.isDirectory() && !e.name.startsWith("."))
    .map((e) => e.name);
};

const main = async () => {
  const projects = await listProjects();
  const registry = {};

  await rm(publicBundles, { recursive: true, force: true });
  await mkdir(publicBundles, { recursive: true });

  for (const id of projects) {
    const dir = path.join(inputDir, id);
    const styleguide = await readJson(path.join(dir, "styleguide.json"));
    const content = await readJson(path.join(dir, "content.json"));
    const prompt = await readText(path.join(dir, "prompt.txt"));

    let files = [];
    const sourcesDir = path.join(dir, "sources");
    const hasSources = await stat(sourcesDir).then(
      (s) => s.isDirectory(),
      () => false,
    );
    if (hasSources) {
      files = (await walkFiles(sourcesDir)).map((f) => `sources/${f}`);
      await cp(sourcesDir, path.join(publicBundles, id, "sources"), {
        recursive: true,
      });
    }

    registry[id] = { styleguide, content, prompt, files };
    console.log(
      `bundle "${id}": styleguide=${Boolean(styleguide)} content=${Boolean(content)} prompt=${Boolean(prompt)} assets=${files.length}`,
    );
  }

  const header = [
    "// AUTO-GENERATED by scripts/generate-bundles.mjs. Do not edit by hand.",
    '// Run `npm run bundles` to regenerate after changing anything in input/.',
    'import type { RawBundle } from "./projectLoader";',
    "",
    "",
  ].join("\n");

  const body = `export const BUNDLE_REGISTRY: Record<string, RawBundle> = ${JSON.stringify(
    registry,
    null,
    2,
  )};\n\nexport const BUNDLE_IDS: string[] = Object.keys(BUNDLE_REGISTRY);\n`;

  await writeFile(outFile, header + body, "utf8");
  console.log(`Wrote ${toPosix(path.relative(root, outFile))}`);
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
