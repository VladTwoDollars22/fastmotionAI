/**
 * Reusable, prop-driven Sound Library registry.
 *
 * Every downloaded/generated SFX or music asset lives in the shared public
 * library and is referenced here by a stable id, so scenes never hardcode file
 * paths. Assets are served through `staticFile()` from `public/`:
 *   - SFX:   `public/assets/audio/sfx/<base>_<variant>.(mp3|wav)`
 *   - Music: `public/assets/audio/music/<base>_<variant>.(mp3|wav)`
 *
 * The 30 SFX are generated by `scripts/generate-audio-library.mjs` (deterministic,
 * royalty-free) and grouped into 5 categories (category + default gain metadata).
 * Default gains are tuned to 0.2–0.6 for soft, high-end SaaS playback
 * (`rules/03_audio_and_sfx.md` §5.1).
 *
 * Rule anchors: `rules/03_audio_and_sfx.md` §0/§0.1/§5.1 and
 * `rules/roles/02_motion_designer.md` §3.1.
 *
 * Note: written as `.ts` (no JSX); helper components use `createElement`.
 */

