/** Stable union of every library id (new assets + legacy aliases). */
export type SfxId = keyof typeof SFX_LIBRARY;

/** Every known id as a runtime array. */
export const SFX_IDS = Object.keys(SFX_LIBRARY) as SfxId[];

/** The 5 library categories, in display order. */
export const SFX_CATEGORIES: SfxCategory[] = ["clicks", "whoosh", "pops", "counters", "impacts"];

/** Ids belonging to one category. */
export const sfxIdsByCategory = (category: SfxCategory): SfxId[] =>
  SFX_IDS.filter((id) => SFX_LIBRARY[id].category === category);

/** Assets belonging to one category. */
export const sfxByCategory = (category: SfxCategory): SfxAsset[] =>
  sfxIdsByCategory(category).map((id) => SFX_LIBRARY[id]);

export const getSfx = (id: SfxId): SfxAsset => SFX_LIBRARY[id];

